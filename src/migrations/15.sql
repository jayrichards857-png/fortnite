
CREATE TABLE case_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id BIGINT NOT NULL REFERENCES cases(id),
  kind TEXT NOT NULL CHECK (kind IN ('order_snapshot')),
  content TEXT NOT NULL,
  sha256 TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_case_records ON case_records(case_id, id);

-- triggers (ported from SQLite RAISE(ABORT) triggers; same messages, same firing rules)
CREATE TRIGGER case_records_no_update BEFORE UPDATE ON case_records FOR EACH ROW
  EXECUTE FUNCTION pp_abort('case records are append-only');
CREATE TRIGGER case_records_no_delete BEFORE DELETE ON case_records FOR EACH ROW
  EXECUTE FUNCTION pp_abort('case records are append-only');
