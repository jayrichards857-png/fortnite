-- Photo reviews: star rating + up to 3 photos of the received item per review.
-- Photos live in PostgreSQL (bytea), not on the web server's disk, so they survive redeploys and work on read-only/serverless hosts such as Vercel.
ALTER TABLE seller_reviews ADD COLUMN rating SMALLINT CHECK (rating IS NULL OR rating BETWEEN 1 AND 5);

CREATE TABLE review_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  review_id BIGINT REFERENCES seller_reviews(id),          -- NULL until the review is posted (a pending upload)
  mime TEXT NOT NULL CHECK (mime IN ('image/jpeg','image/png','image/webp')),
  bytes INTEGER NOT NULL CHECK (bytes BETWEEN 1 AND 4194304),
  width INTEGER NOT NULL,
  height INTEGER NOT NULL,
  data BYTEA NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','published','removed')),
  removed_by BIGINT REFERENCES users(id),
  removed_at BIGINT,
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_review_photos_review ON review_photos(review_id) WHERE review_id IS NOT NULL;
CREATE INDEX idx_review_photos_pending ON review_photos(user_id, created_at) WHERE review_id IS NULL;

-- Backstop for the 3-photo limit: whatever code path attaches a photo, a review can never carry more than three live ones.
CREATE FUNCTION pp_review_photo_limit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.review_id IS NOT NULL AND NEW.status <> 'removed'
     AND (SELECT COUNT(*) FROM review_photos p WHERE p.review_id = NEW.review_id AND p.status <> 'removed' AND p.id <> NEW.id) >= 3 THEN
    RAISE EXCEPTION 'a review can have at most 3 photos';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER review_photos_max3 BEFORE INSERT OR UPDATE OF review_id, status ON review_photos
  FOR EACH ROW EXECUTE FUNCTION pp_review_photo_limit();

-- The history of a review now also records staff removing a single photo.
ALTER TABLE review_events DROP CONSTRAINT review_events_kind_check;
ALTER TABLE review_events ADD CONSTRAINT review_events_kind_check
  CHECK (kind IN ('created','edited','removed','reinstated','reported','hidden','restored','report_dismissed','photo_removed'));
