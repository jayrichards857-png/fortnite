-- HARD SELLER CAP, enforced by the database so no code path or race can exceed it. The cap lives in settings (default 3).
-- It only blocks NEW sellers; existing rows are never touched, so a database that somehow already has more is preserved.
INSERT INTO settings(key, value) VALUES ('seller_cap', '3') ON CONFLICT DO NOTHING;

-- triggers (ported from SQLite RAISE(ABORT) triggers; same messages, same firing rules)
CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit_log FOR EACH ROW
  EXECUTE FUNCTION pp_abort('audit log is append-only');
CREATE TRIGGER audit_no_delete BEFORE DELETE ON audit_log FOR EACH ROW
  EXECUTE FUNCTION pp_abort('audit log is append-only');
CREATE TRIGGER case_events_no_update BEFORE UPDATE ON case_events FOR EACH ROW
  EXECUTE FUNCTION pp_abort('case events are append-only');
CREATE TRIGGER case_events_no_delete BEFORE DELETE ON case_events FOR EACH ROW
  EXECUTE FUNCTION pp_abort('case events are append-only');
CREATE TRIGGER case_events_internal_admin_only BEFORE INSERT ON case_events FOR EACH ROW
  WHEN (NEW.internal = 1 AND NEW.actor_role <> 'admin')
  EXECUTE FUNCTION pp_abort('internal notes are admin-only');
CREATE TRIGGER invitations_token_immutable BEFORE UPDATE OF token_hash, email, kind ON invitations FOR EACH ROW
  EXECUTE FUNCTION pp_abort('invitation identity is immutable');

-- Seller cap. The advisory lock serialises concurrent seller creation so two transactions cannot both pass the count check.
CREATE FUNCTION pp_seller_cap() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.is_seller <> 1 THEN RETURN NEW; END IF;
  ELSIF NOT (NEW.is_seller = 1 AND OLD.is_seller = 0) THEN
    RETURN NEW;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('pairplug:seller_cap'));
  IF (SELECT COUNT(*) FROM users WHERE is_seller = 1) >= COALESCE((SELECT CAST(value AS BIGINT) FROM settings WHERE key = 'seller_cap'), 3) THEN
    RAISE EXCEPTION 'seller cap reached' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER sellers_cap_insert BEFORE INSERT ON users FOR EACH ROW EXECUTE FUNCTION pp_seller_cap();
CREATE TRIGGER sellers_cap_update BEFORE UPDATE OF is_seller ON users FOR EACH ROW EXECUTE FUNCTION pp_seller_cap();
