
ALTER TABLE users ADD COLUMN selling_restricted_at BIGINT;
ALTER TABLE users ADD COLUMN selling_restricted_reason TEXT;
ALTER TABLE users ADD COLUMN selling_restricted_case BIGINT;
ALTER TABLE cases ADD COLUMN category TEXT CHECK (category IS NULL OR category IN ('non_delivery','payment_not_confirmed','not_as_described','counterfeit','fake_payment_or_tracking','suspected_scam','other'));
CREATE INDEX idx_cases_subject ON cases(subject_user_id, status);
CREATE TABLE processor_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id BIGINT NOT NULL REFERENCES cases(id),
  seller_id BIGINT NOT NULL REFERENCES users(id),
  provider TEXT NOT NULL CHECK (provider IN ('stripe','paypal','other')),
  provider_host TEXT,
  status TEXT NOT NULL DEFAULT 'prepared' CHECK (status IN ('prepared','submitted')),
  packet TEXT NOT NULL,
  events_through BIGINT NOT NULL,
  prepared_by BIGINT NOT NULL REFERENCES users(id),
  prepared_at BIGINT NOT NULL,
  submitted_by BIGINT REFERENCES users(id),
  submitted_at BIGINT,
  channel TEXT, reference TEXT, note TEXT
);
CREATE UNIQUE INDEX idx_processor_reports_pending ON processor_reports(case_id, provider) WHERE status = 'prepared';

-- triggers (ported from SQLite RAISE(ABORT) triggers; same messages, same firing rules)
CREATE TRIGGER processor_reports_no_delete BEFORE DELETE ON processor_reports FOR EACH ROW
  EXECUTE FUNCTION pp_abort('processor reports are append-only');
CREATE TRIGGER processor_reports_frozen BEFORE UPDATE ON processor_reports FOR EACH ROW
  WHEN (OLD.status = 'submitted' OR NEW.case_id <> OLD.case_id OR NEW.packet <> OLD.packet OR NEW.provider <> OLD.provider OR NEW.prepared_at <> OLD.prepared_at)
  EXECUTE FUNCTION pp_abort('a submitted processor report cannot be changed');
