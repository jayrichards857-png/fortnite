-- Moderator capacity (active moderators + unused, unexpired setup links <= cap). One advisory lock covers both tables so the combined count is exact.
CREATE FUNCTION pp_moderator_cap_user() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.is_moderator <> 1 THEN RETURN NEW; END IF;
  ELSIF NOT (NEW.is_moderator = 1 AND OLD.is_moderator = 0) THEN
    RETURN NEW;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('pairplug:moderator_cap'));
  IF (SELECT COUNT(*) FROM users WHERE is_moderator = 1) >= COALESCE((SELECT CAST(value AS BIGINT) FROM settings WHERE key = 'moderator_cap'), 5) THEN
    RAISE EXCEPTION 'moderator cap reached' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER moderators_cap_insert BEFORE INSERT ON users FOR EACH ROW EXECUTE FUNCTION pp_moderator_cap_user();
CREATE TRIGGER moderators_cap_update BEFORE UPDATE OF is_moderator ON users FOR EACH ROW EXECUTE FUNCTION pp_moderator_cap_user();
CREATE FUNCTION pp_moderator_cap_invite() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('pairplug:moderator_cap'));
  IF (SELECT COUNT(*) FROM users WHERE is_moderator = 1)
     + (SELECT COUNT(*) FROM moderator_invites WHERE used_at IS NULL AND revoked_at IS NULL AND expires_at > CAST(EXTRACT(EPOCH FROM now()) AS BIGINT))
     >= COALESCE((SELECT CAST(value AS BIGINT) FROM settings WHERE key = 'moderator_cap'), 5) THEN
    RAISE EXCEPTION 'moderator slots exhausted' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER moderator_invites_cap BEFORE INSERT ON moderator_invites FOR EACH ROW EXECUTE FUNCTION pp_moderator_cap_invite();
