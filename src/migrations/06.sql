
CREATE TABLE seller_ship_from (
  user_id BIGINT PRIMARY KEY REFERENCES users(id),
  name TEXT NOT NULL, line1 TEXT NOT NULL, line2 TEXT, city TEXT NOT NULL, region TEXT NOT NULL, postal TEXT NOT NULL,
  country TEXT NOT NULL CHECK (country IN ('US','CA','MX')), phone TEXT, updated_at BIGINT NOT NULL
);
CREATE TABLE shipments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  seller_id BIGINT NOT NULL REFERENCES users(id),
  provider TEXT NOT NULL DEFAULT 'shippo',
  test BIGINT NOT NULL CHECK (test IN (0,1)),
  status TEXT NOT NULL CHECK (status IN ('rates_ready','purchasing','success','failed','superseded')),
  weight_oz DOUBLE PRECISION NOT NULL, length_in DOUBLE PRECISION NOT NULL, width_in DOUBLE PRECISION NOT NULL, height_in DOUBLE PRECISION NOT NULL,
  address_hash TEXT NOT NULL,
  provider_shipment_id TEXT, rates_json TEXT, rates_fetched_at BIGINT,
  selected_rate_id TEXT, carrier TEXT, service TEXT, price_cents BIGINT, currency TEXT,
  provider_transaction_id TEXT, label_url TEXT, tracking_number TEXT, tracking_url TEXT, tracking_status TEXT,
  error_message TEXT, confirmed_at BIGINT, purchased_at BIGINT,
  created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE INDEX idx_shipments_order ON shipments(order_id, id);
-- At most one in-flight or completed purchase per order and mode: this is what makes double clicks and retries safe.
CREATE UNIQUE INDEX idx_shipments_one_purchase ON shipments(order_id, test) WHERE status IN ('purchasing','success');

-- triggers (ported from SQLite RAISE(ABORT) triggers; same messages, same firing rules)
CREATE TRIGGER shipments_no_delete BEFORE DELETE ON shipments FOR EACH ROW
  EXECUTE FUNCTION pp_abort('shipments cannot be deleted');
CREATE TRIGGER shipments_label_immutable BEFORE UPDATE OF order_id, seller_id, test, price_cents, currency, carrier, service, label_url, tracking_number, provider_transaction_id ON shipments FOR EACH ROW
  WHEN (OLD.status = 'success')
  EXECUTE FUNCTION pp_abort('a purchased label cannot be changed');
