
CREATE TABLE external_sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id BIGINT NOT NULL REFERENCES listings(id),
  seller_id BIGINT NOT NULL REFERENCES users(id),
  sold_on TEXT NOT NULL CHECK (sold_on ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  price_cents BIGINT CHECK (price_cents IS NULL OR (price_cents >= 0 AND price_cents <= 100000000)),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency = 'USD'),
  channel TEXT, reference TEXT, note TEXT,
  recorded_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX idx_external_sales_listing ON external_sales(listing_id);
CREATE INDEX idx_external_sales_seller ON external_sales(seller_id, sold_on DESC, id DESC);

-- triggers (ported from SQLite RAISE(ABORT) triggers; same messages, same firing rules)
CREATE TRIGGER external_sales_no_delete BEFORE DELETE ON external_sales FOR EACH ROW
  EXECUTE FUNCTION pp_abort('external sale records cannot be deleted');
CREATE TRIGGER external_sales_no_update BEFORE UPDATE ON external_sales FOR EACH ROW
  EXECUTE FUNCTION pp_abort('external sale records cannot be changed');
