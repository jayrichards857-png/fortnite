CREATE TRIGGER seller_reviews_identity_immutable BEFORE UPDATE OF order_id, buyer_id, seller_id, created_at ON seller_reviews FOR EACH ROW
  EXECUTE FUNCTION pp_abort('review identity is immutable');
CREATE TRIGGER seller_reviews_no_delete BEFORE DELETE ON seller_reviews FOR EACH ROW
  EXECUTE FUNCTION pp_abort('reviews are never deleted');
CREATE TRIGGER review_events_no_update BEFORE UPDATE ON review_events FOR EACH ROW
  EXECUTE FUNCTION pp_abort('review history is append-only');
CREATE TRIGGER review_events_no_delete BEFORE DELETE ON review_events FOR EACH ROW
  EXECUTE FUNCTION pp_abort('review history is append-only');

CREATE FUNCTION pp_review_eligible() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM orders o WHERE o.id = NEW.order_id AND o.buyer_id = NEW.buyer_id AND o.seller_id = NEW.seller_id AND o.status IN ('delivered','released')) THEN
    RAISE EXCEPTION 'review requires the buyer''s own completed order' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER seller_reviews_eligible BEFORE INSERT ON seller_reviews FOR EACH ROW EXECUTE FUNCTION pp_review_eligible();
