-- Self-service seller access with administrator approval, and NO limit on the number of sellers.
-- Members apply; an administrator approves or rejects. Request statuses: pending | approved | rejected | withdrawn (no capacity queue).
CREATE TABLE seller_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  store_name TEXT NOT NULL,
  handle TEXT NOT NULL,
  country TEXT NOT NULL,
  region TEXT NOT NULL,
  city TEXT NOT NULL,
  bio TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','withdrawn')),
  decision_note TEXT,
  decided_by BIGINT REFERENCES users(id),
  decided_at BIGINT,
  created_at BIGINT NOT NULL
);
-- One open request per person, enforced by the database (a double click or two tabs cannot create two).
CREATE UNIQUE INDEX idx_seller_applications_one_open ON seller_applications(user_id) WHERE status = 'pending';
CREATE INDEX idx_seller_applications_queue ON seller_applications(status, id);

-- The beta seller cap (3) is removed: no arbitrary numerical limit on sellers. Existing sellers and all data are untouched.
DROP TRIGGER sellers_cap_insert ON users;
DROP TRIGGER sellers_cap_update ON users;
DROP FUNCTION pp_seller_cap();
