CREATE TABLE sale_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT NOT NULL REFERENCES external_sales(id),
  actor_id BIGINT NOT NULL REFERENCES users(id),
  action TEXT NOT NULL,
  detail TEXT,
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_sale_events ON sale_events(sale_id, id);

-- triggers (ported from SQLite RAISE(ABORT) triggers; same messages, same firing rules)
CREATE TRIGGER external_sales_identity_immutable BEFORE UPDATE OF listing_id, seller_id, recorded_at, origin ON external_sales FOR EACH ROW
  EXECUTE FUNCTION pp_abort('a sale record''s listing, seller, origin and creation time cannot be changed');
CREATE TRIGGER external_sales_void_final BEFORE UPDATE ON external_sales FOR EACH ROW
  WHEN (OLD.voided_at IS NOT NULL)
  EXECUTE FUNCTION pp_abort('voided sale records cannot be changed');
CREATE TRIGGER sale_events_no_update BEFORE UPDATE ON sale_events FOR EACH ROW
  EXECUTE FUNCTION pp_abort('sale history is append-only');
CREATE TRIGGER sale_events_no_delete BEFORE DELETE ON sale_events FOR EACH ROW
  EXECUTE FUNCTION pp_abort('sale history is append-only');
