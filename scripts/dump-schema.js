'use strict';
// Regenerates docs/schema.sql from the migrations: applies them to a THROWAWAY database on the server named by PAIRPLUG_TEST_PG
// (admin URL, default postgres://postgres@127.0.0.1:5432/postgres; see scripts/pg-test.sh) and runs `pg_dump --schema-only`.
//   node scripts/dump-schema.js
const fs = require('node:fs');
const path = require('node:path');
const testdb = require('../test/testdb');
const { runTool } = require('./lib/pg');
const created = testdb.createSync();
process.env.DATABASE_URL = created.url;
const db = require('../src/db');
(async () => {
  await db.ready();
  const sql = runTool('pg_dump', ['--schema-only', '--no-owner', '--no-privileges', '--no-comments'], created.url);
  const body = sql.split('\n').filter((l) => !/^(SET |SELECT pg_catalog\.set_config|\\(un)?restrict)/.test(l)).join('\n').replace(/\n{3,}/g, '\n\n').trim();
  fs.writeFileSync(path.join(__dirname, '..', 'docs', 'schema.sql'), `-- Generated by scripts/dump-schema.js (pg_dump --schema-only) after applying src/migrations 01..${String(db.MIGRATIONS.length).padStart(2, '0')} (schema version ${db.MIGRATIONS.length}). Do not edit by hand.\n\n${body}\n`);
  console.log(`docs/schema.sql written (schema v${db.MIGRATIONS.length})`);
})().catch((e) => { console.error(e); process.exitCode = 1; }).finally(async () => { await db.close(); testdb.dropSync(created.name); });
