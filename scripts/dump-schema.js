'use strict';
// Regenerates docs/schema.sql from the migrations on a throwaway in-memory database.   node scripts/dump-schema.js
const fs = require('node:fs');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');
process.env.PAIRPLUG_DB = ':memory:';
const { MIGRATIONS } = require('../src/db');
const db = new DatabaseSync(':memory:');
for (const m of MIGRATIONS) db.exec(m);
const rows = db.prepare("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, name").all();
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'schema.sql'), `-- Generated by scripts/dump-schema.js from MIGRATIONS (schema version ${MIGRATIONS.length}). Do not edit by hand.\n\n${rows.map((r) => r.sql + ';').join('\n\n')}\n`);
console.log(`docs/schema.sql written (schema v${MIGRATIONS.length}, ${rows.length} objects)`);
